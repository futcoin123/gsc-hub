/** Название языка по атрибуту lang: «es-ES» → Spanish, «zh-TW» → Chinese (Traditional). */
export function languageName(lang: string | null | undefined): string | null {
  const v = (lang ?? '').trim().toLowerCase().replace(/_/g, '-');
  if (!v) return null;
  const [base, ...rest] = v.split('-');
  if (base === 'zh') return rest.some((x) => ['tw', 'hk', 'mo', 'hant'].includes(x)) ? 'Chinese (Traditional)' : 'Chinese (Simplified)';
  return LANGUAGE[base] ?? null;
}

/** Страна из региона в lang: «de-AT» → AT, «en-GB» → GB; без региона — null. */
export function langRegion(lang: string | null | undefined): string | null {
  const m = /^[a-z]{2,3}[-_]([a-z]{2})\b/i.exec((lang ?? '').trim());
  const c = m?.[1].toUpperCase() ?? null;
  return c && COUNTRY[c] ? c : null;
}

