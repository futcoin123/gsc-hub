// Двухбуквенные зоны, которые обычно берут не ради страны.
const GENERIC_CC = new Set(['co', 'io', 'gg', 'me', 'tv', 'ai', 'fm', 'ly', 'to', 'cc', 'ws', 'nu', 'la', 'sh', 'ac', 'im', 'ag', 'sc', 'vc', 'gl']);

/** Страна по зоне домена: futcoin.de → DE, futcoins.co.uk → GB; .com, .eu, .gg — null. */
export function tldCountry(host: string): string | null {
  const tld = host.toLowerCase().replace(/\.$/, '').split('.').pop() ?? '';
  if (tld === 'uk') return 'GB';
  if (tld.length !== 2 || GENERIC_CC.has(tld)) return null;
  const c = tld.toUpperCase();
  return COUNTRY[c] ? c : null;
}
