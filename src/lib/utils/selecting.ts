// Строки таблиц, которые раскрываются по нажатию, не должны сворачиваться,
// когда в них выделяют текст, чтобы скопировать (просьба владелицы 17.11.2026:
// скопировала ключ — строка свернулась, а нужно вставить ключ и ссылку ниже).

/** На странице выделен текст — нажатие было выделением, а не нажатием на строку. */
export function selecting(): boolean {
  if (typeof window === 'undefined') return false;
  const s = window.getSelection();
  return !!s && !s.isCollapsed && s.toString().trim() !== '';
}
